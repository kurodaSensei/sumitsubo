// `npx sumitsubo rules` — generate rules for other agents from the same skills.
//
// Cursor:  .cursor/rules/sumitsubo.mdc (always on) + one agent-requested rule per skill.
// Codex and any AGENTS.md reader: a managed block in AGENTS.md with the kernel and
//          an index of skills, whose files live in .sumitsubo/skills/.
//
// What translates: the always-on rules, the standards, references, templates and
// the Node scripts. What does not: slash commands, hooks, subagents and model
// routing are Claude Code features, so those skills are left out and the rest say so.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG_ROOT = fileURLToPath(new URL('..', import.meta.url));
const SKIP = new Set(['model-routing', 'output', 'claude-design-bridge']);
const MARK = 'generated by sumitsubo';

const read = (p) => readFileSync(p, 'utf8');
function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  const fm = {};
  if (m) for (const line of m[1].split('\n')) { const k = line.match(/^([\w-]+):\s*(.*)$/); if (k) fm[k[1]] = k[2].replace(/^"(.*)"$/, '$1'); }
  return { fm, body: m ? text.slice(m[0].length) : text };
}

// Paths inside a skill are written for an installed plugin; point them at .sumitsubo/.
const NOTE = '> Exported from Sumitsubo. Mentions of `/sumi:*` commands, hooks or subagents describe Claude Code; outside it, do the equivalent step by hand.\n';
function rewrite(body, skill) {
  return NOTE + body
    .replace(/\$\{CLAUDE_PLUGIN_ROOT\}\/skills\//g, '.sumitsubo/skills/')
    .replace(/\$\{CLAUDE_PLUGIN_ROOT\}\/templates\//g, '.sumitsubo/templates/')
    .replace(/\$\{CLAUDE_PLUGIN_ROOT\}\/scripts\//g, '.sumitsubo/scripts/')
    .replace(/(?<![\w/.-])references\//g, `.sumitsubo/skills/${skill}/references/`)
    .replace(/(?<![\w/.-])scripts\/(?=[\w-]+\.mjs)/g, `.sumitsubo/skills/${skill}/scripts/`)
    // `sumi:a11y` / `sumi-design:anti-slop` → the exported names; `/sumi:review` stays (a command).
    .replace(/(?<![\w/])sumi(?:-[a-z]+)?:([a-z][\w-]*)/g, 'sumi-$1');
}

export function collectSkills(plugins) {
  const out = [];
  for (const plugin of plugins) {
    const dir = join(PKG_ROOT, 'plugins', plugin, 'skills');
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir).sort()) {
      const file = join(dir, name, 'SKILL.md');
      if (!existsSync(file) || SKIP.has(name)) continue;
      const { fm, body } = frontmatter(read(file));
      out.push({ plugin, name, dir: join(dir, name), description: fm.description ?? '', body });
    }
  }
  return out;
}

function projectFacts(cwd, stacks) {
  const has = (f) => existsSync(join(cwd, f));
  const pm = has('pnpm-lock.yaml') ? 'pnpm' : has('yarn.lock') ? 'yarn' : has('bun.lock') || has('bun.lockb') ? 'bun' : has('package-lock.json') ? 'npm' : null;
  let scripts = {};
  try { scripts = JSON.parse(read(join(cwd, 'package.json'))).scripts ?? {}; } catch { /* no package.json */ }
  const run = (s) => (scripts[s] ? `${pm ?? 'npm'} run ${s}` : null);
  const cmds = ['dev', 'build', 'test', 'lint'].map((s) => [s, run(s)]).filter(([, c]) => c);
  return [
    `- Stack: ${stacks.length ? stacks.join(', ') : 'not detected'}`,
    pm ? `- Package manager: ${pm}` : null,
    cmds.length ? `- Commands: ${cmds.map(([s, c]) => `${s} \`${c}\``).join(' · ')}` : null,
  ].filter(Boolean).join('\n');
}

function kernel(version, facts, agent) {
  return `## Sumitsubo framework

This project follows the Sumitsubo framework (v${version}), exported for ${agent}. Slash commands, hooks, subagents and model routing are Claude Code features and are not available here: apply the same process by hand.

**Communication.** Talk to the user in their language. Code, identifiers, commits, comments and technical docs in English.

**Workflow.** Help the user decide; do not use every capability by default. Before implementing anything, apply \`sumi-workflow\` (including the scope check against the literal request): classify the request (direct / single focused change / feature file), refute uncertainty with evidence before asking, keep each slice around 400 changed lines, assess risk before each commit. Feature files live in \`.sumi/tasks/\` (template: \`.sumitsubo/templates/feature.md\`).

**Quality bar.** Follow \`sumi-code-quality\` on every change. No speculative abstractions, no dead code, no invented APIs. Build the simple version and mark deliberate simplifications with \`ponytail: <what>; extend when <trigger>\` comments. Accessibility (WCAG 2.2 AA, \`sumi-a11y\`) and performance budgets (\`sumi-performance\`) are acceptance criteria, not polish.

**Design.** Any visual or UI work starts from \`DESIGN.md\` (\`sumi-design-direction\`). Never introduce fonts, colors, radii, shadows or motion that are not tokens there. If \`DESIGN.md\` does not exist and the task is visual, propose the direction process first.

**Done means verified.** Run the checks (types, lint, tests, build) and show evidence before saying something works. Pages: \`node .sumitsubo/scripts/evidence.mjs <url> --routes /\` (screenshots, axe, Lighthouse).

**Project facts:**
${facts}`;
}

function upsertBlock(file, block, version) {
  const begin = `<!-- sumi:begin v${version} — ${MARK}; edit outside this block. -->`;
  const full = `${begin}\n${block}\n<!-- sumi:end -->`;
  const current = existsSync(file) ? read(file) : '';
  const re = /<!-- sumi:begin[\s\S]*?<!-- sumi:end -->/;
  const next = re.test(current) ? current.replace(re, full) : current ? `${full}\n\n${current}` : `${full}\n`;
  writeFileSync(file, next);
}

// Shared payload: every exported skill folder (references, scripts), templates, scripts.
function writeShared(out, skills, plugins) {
  const dest = join(out, '.sumitsubo');
  rmSync(dest, { recursive: true, force: true });
  for (const s of skills) {
    cpSync(s.dir, join(dest, 'skills', s.name), { recursive: true, filter: (p) => !p.endsWith('SKILL.md') });
    writeFileSync(join(dest, 'skills', s.name, 'SKILL.md'),
      `---\nname: sumi-${s.name}\ndescription: ${JSON.stringify(s.description)}\n---\n<!-- ${MARK} from ${s.plugin}/${s.name}; regenerate with npx sumitsubo rules -->\n${rewrite(s.body, s.name)}`);
  }
  for (const p of plugins) {
    for (const kind of ['templates', 'scripts']) {
      const src = join(PKG_ROOT, 'plugins', p, kind);
      if (existsSync(src)) cpSync(src, join(dest, kind), { recursive: true });
    }
  }
  rmSync(join(dest, 'templates', 'CLAUDE.managed.md'), { force: true });
  writeFileSync(join(dest, 'README.md'), `# .sumitsubo\n\n${MARK}: skills, templates and scripts used by the rules in this project. Regenerate with \`npx sumitsubo rules\`; do not edit by hand.\n`);
  return dest;
}

export function exportRules({ cwd, targets, stacks, version, dryRun, log }) {
  const plugins = ['sumi', 'sumi-design', ...stacks.map((s) => `sumi-${s}`)];
  const skills = collectSkills(plugins);
  const facts = projectFacts(cwd, stacks);
  const written = [];
  if (dryRun) {
    log(`  would write .sumitsubo/ (${skills.length} skills, templates, scripts)`);
    if (targets.includes('cursor')) log(`  would write .cursor/rules/sumitsubo.mdc + ${skills.length} sumi-*.mdc rules`);
    if (targets.includes('codex')) log('  would add or update the sumitsubo block in AGENTS.md');
    return { skills: skills.length, written };
  }
  written.push(relative(cwd, writeShared(cwd, skills, plugins)) + '/');

  if (targets.includes('cursor')) {
    const dir = join(cwd, '.cursor', 'rules');
    mkdirSync(dir, { recursive: true });
    for (const f of readdirSync(dir).filter((f) => /^sumi(tsubo|-[\w-]+)\.mdc$/.test(f))) {
      if (read(join(dir, f)).includes(MARK)) rmSync(join(dir, f)); // our own previous output only
    }
    writeFileSync(join(dir, 'sumitsubo.mdc'), `---\ndescription: Sumitsubo framework — always-on rules\nalwaysApply: true\n---\n<!-- ${MARK} v${version} -->\n${kernel(version, facts, 'Cursor')}\n`);
    written.push('.cursor/rules/sumitsubo.mdc');
    for (const s of skills) {
      const desc = JSON.stringify(s.description.replace(/\n/g, ' '));
      writeFileSync(join(dir, `sumi-${s.name}.mdc`), `---\ndescription: ${desc}\nalwaysApply: false\n---\n<!-- ${MARK} v${version} from ${s.plugin}/${s.name} -->\n${rewrite(s.body, s.name)}`);
    }
    written.push(`.cursor/rules/sumi-*.mdc (${skills.length})`);
  }

  if (targets.includes('codex')) {
    const index = skills.map((s) => `- \`sumi-${s.name}\` → \`.sumitsubo/skills/${s.name}/SKILL.md\` — ${s.description.split(/(?<=\.)\s/)[0]}`).join('\n');
    const block = `${kernel(version, facts, 'Codex and other AGENTS.md agents')}

**Skills.** Before a task, read the skill file whose description matches it; each one carries the standards, slop tells and a Done checklist.
${index}`;
    upsertBlock(join(cwd, 'AGENTS.md'), block, version);
    written.push('AGENTS.md (sumitsubo block)');
  }
  return { skills: skills.length, written };
}

